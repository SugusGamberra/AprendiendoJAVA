package Calculo;

public class areaRectangulo {

	public static void calculaArea(int base, int altura) {
		// Creamos un método llamado calculaArea, y dentro le declaramos las variables
		// Estas variables son de tipo Integer (numeros enteros)
		// Este método crea un espacio de memoria para hacer el calculo
		
		int area = base * altura;
		
		// Así concatenamos un texto con variable:
		
		System.out.println("El área del rectángulo es: " + area);
		
		
	}

}
